import { chromium } from '@playwright/test';
const b = await chromium.launch({ channel: 'chrome' });
const ctx = await b.newContext({ viewport: { width: 760, height: 900 }, locale: 'zh-TW', deviceScaleFactor: 1.5 });
const p = await ctx.newPage();
const base = 'http://localhost:4190';
await p.goto(`${base}/#/quiz/10`);
await p.getByRole('heading', { name: '情境' }).waitFor();
await p.screenshot({ path: 'screenshots/A-緊急命令-題目頁.png', fullPage: true });
await p.getByLabel(/^總統情況最清楚/).check();
await p.getByRole('button', { name: '確認答案' }).click();
await p.locator('#result-h').waitFor();
await p.screenshot({ path: 'screenshots/B-緊急命令-答案頁.png', fullPage: true });
await p.goto(`${base}/#/quiz/9`);
await p.getByRole('heading', { name: '情境' }).waitFor();
await p.screenshot({ path: 'screenshots/C-沒有定論-題目頁.png', fullPage: true });
await p.getByLabel(/^兩項都盡力去做/).check();
await p.getByRole('button', { name: '確認我的想法' }).click();
await p.locator('#result-h').waitFor();
await p.screenshot({ path: 'screenshots/D-沒有定論-答案頁.png', fullPage: true });
await p.goto(`${base}/#/quiz/1`);
await p.getByRole('heading', { name: '情境' }).waitFor();
await p.screenshot({ path: 'screenshots/E-預算-題目頁.png', fullPage: true });
await b.close();
console.log('ok');
